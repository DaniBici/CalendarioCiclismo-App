CREATE OR REPLACE FUNCTION private.start_automation_run(
  p_job text,
  p_trigger_kind text,
  p_request_id bigint DEFAULT NULL,
  p_revision text DEFAULT NULL
)
RETURNS bigint
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_id bigint;
BEGIN
  IF session_user = 'cc_results_worker' AND p_job NOT IN ('results', 'uci_team_ranking') THEN
    RAISE EXCEPTION 'Trabajo no autorizado para cc_results_worker' USING ERRCODE = '42501';
  ELSIF session_user = 'cc_broadcasts_login' AND p_job <> 'broadcasts' THEN
    RAISE EXCEPTION 'Trabajo no autorizado para cc_broadcasts_login' USING ERRCODE = '42501';
  ELSIF session_user NOT IN ('cc_results_worker', 'cc_broadcasts_login') THEN
    RAISE EXCEPTION 'Worker no autorizado' USING ERRCODE = '42501';
  END IF;

  INSERT INTO private.automation_runs (job, trigger_kind, request_id, revision)
  VALUES (p_job, p_trigger_kind, p_request_id, NULLIF(left(p_revision, 80), ''))
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$function$;

CREATE OR REPLACE FUNCTION private.record_automation_source_run(
  p_run_id bigint,
  p_source text,
  p_status text,
  p_items_found integer DEFAULT 0,
  p_items_matched integer DEFAULT 0,
  p_items_changed integer DEFAULT 0,
  p_errors integer DEFAULT 0,
  p_summary jsonb DEFAULT '{}'::jsonb
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_job text;
BEGIN
  SELECT job INTO v_job FROM private.automation_runs WHERE id = p_run_id;
  IF (session_user = 'cc_results_worker' AND v_job NOT IN ('results', 'uci_team_ranking'))
     OR (session_user = 'cc_broadcasts_login' AND v_job <> 'broadcasts')
     OR session_user NOT IN ('cc_results_worker', 'cc_broadcasts_login') THEN
    RAISE EXCEPTION 'Ejecución no autorizada para este worker' USING ERRCODE = '42501';
  END IF;

  INSERT INTO private.automation_source_runs (
    run_id, source, status, items_found, items_matched, items_changed, errors, summary
  ) VALUES (
    p_run_id, p_source, p_status, p_items_found, p_items_matched,
    p_items_changed, p_errors, COALESCE(p_summary, '{}'::jsonb)
  )
  ON CONFLICT (run_id, source) DO UPDATE SET
    status = EXCLUDED.status,
    items_found = EXCLUDED.items_found,
    items_matched = EXCLUDED.items_matched,
    items_changed = EXCLUDED.items_changed,
    errors = EXCLUDED.errors,
    summary = EXCLUDED.summary;
END;
$function$;

CREATE OR REPLACE FUNCTION private.finish_automation_run(
  p_run_id bigint,
  p_status text,
  p_summary jsonb DEFAULT '{}'::jsonb,
  p_error text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
  v_job text;
BEGIN
  SELECT job INTO v_job FROM private.automation_runs WHERE id = p_run_id;
  IF (session_user = 'cc_results_worker' AND v_job NOT IN ('results', 'uci_team_ranking'))
     OR (session_user = 'cc_broadcasts_login' AND v_job <> 'broadcasts')
     OR session_user NOT IN ('cc_results_worker', 'cc_broadcasts_login') THEN
    RAISE EXCEPTION 'Ejecución no autorizada para este worker' USING ERRCODE = '42501';
  END IF;

  UPDATE private.automation_runs
  SET finished_at = now(),
      status = p_status,
      summary = COALESCE(p_summary, '{}'::jsonb),
      error_message = CASE WHEN p_status IN ('error', 'partial')
        THEN left(COALESCE(p_error, 'Error sin detalle'), 2000)
        ELSE NULL
      END
  WHERE id = p_run_id
    AND status = 'running';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Ejecución no activa: %', p_run_id;
  END IF;
END;
$function$;

