CREATE OR REPLACE FUNCTION private.dispatch_results_sync(
  p_race_id text,
  p_stage integer,
  p_ignore_window boolean
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  IF NOT (SELECT private.is_admin()) THEN
    RAISE EXCEPTION 'La operación requiere permisos de administración' USING ERRCODE = '42501';
  END IF;
  IF p_race_id IS NOT NULL AND btrim(p_race_id) = '' THEN
    RAISE EXCEPTION 'Falta p_race_id';
  END IF;
  IF p_stage IS NOT NULL AND p_race_id IS NULL THEN
    RAISE EXCEPTION 'Una etapa requiere p_race_id';
  END IF;
  IF p_race_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.races WHERE id = p_race_id
  ) THEN
    RAISE EXCEPTION 'Carrera inexistente: %', p_race_id;
  END IF;

  PERFORM pg_catalog.pg_advisory_xact_lock(pg_catalog.hashtext('results_manual_queue'));
  IF NOT EXISTS (
    SELECT 1
    FROM private.results_manual_queue q
    WHERE q.status IN ('pending', 'running')
      AND q.race_id IS NOT DISTINCT FROM p_race_id
      AND q.stage_number IS NOT DISTINCT FROM p_stage
      AND q.ignore_window = COALESCE(p_ignore_window, false)
  ) THEN
    INSERT INTO private.results_manual_queue (
      race_id, stage_number, ignore_window, requested_by
    ) VALUES (
      p_race_id, p_stage, COALESCE(p_ignore_window, false), (SELECT auth.uid())
    );
  END IF;

  RETURN 'queued';
END;
$function$;

CREATE OR REPLACE FUNCTION private.claim_results_manual_request()
RETURNS TABLE (
  request_id bigint,
  race_id text,
  stage_number integer,
  ignore_window boolean
)
LANGUAGE sql
SECURITY DEFINER
SET search_path = ''
AS $function$
  WITH candidate AS (
    SELECT q.id
    FROM private.results_manual_queue q
    WHERE q.status = 'pending'
       OR (q.status = 'running' AND q.started_at < now() - interval '30 minutes')
    ORDER BY q.requested_at, q.id
    FOR UPDATE SKIP LOCKED
    LIMIT 1
  ), claimed AS (
    UPDATE private.results_manual_queue q
    SET status = 'running',
        started_at = now(),
        finished_at = NULL,
        attempts = q.attempts + 1,
        error_message = NULL
    FROM candidate c
    WHERE q.id = c.id
    RETURNING q.id, q.race_id, q.stage_number, q.ignore_window
  )
  SELECT id, race_id, stage_number, ignore_window FROM claimed;
$function$;

CREATE OR REPLACE FUNCTION private.finish_results_manual_request(
  p_request_id bigint,
  p_success boolean,
  p_error text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
BEGIN
  UPDATE private.results_manual_queue
  SET status = CASE WHEN p_success THEN 'done' ELSE 'error' END,
      finished_at = now(),
      error_message = CASE WHEN p_success THEN NULL ELSE left(COALESCE(p_error, 'Error sin detalle'), 1000) END
  WHERE id = p_request_id
    AND status = 'running';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Solicitud manual no reclamada: %', p_request_id;
  END IF;
END;
$function$;

