-- Los botones manuales de resultados dejan de disparar GitHub Actions.
-- La RPC pública conserva su firma, pero encola una solicitud privada que el
-- watcher del VPS reclama en su siguiente tick.

CREATE TABLE private.uci_results_manual_queue (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  race_id text REFERENCES public.races(id) ON DELETE CASCADE,
  stage_number integer,
  ignore_window boolean NOT NULL DEFAULT false,
  requested_at timestamptz NOT NULL DEFAULT now(),
  requested_by uuid,
  started_at timestamptz,
  finished_at timestamptz,
  attempts integer NOT NULL DEFAULT 0,
  status text NOT NULL DEFAULT 'pending'
    CHECK (status IN ('pending', 'running', 'done', 'error')),
  error_message text,
  CHECK (stage_number IS NULL OR race_id IS NOT NULL)
);

REVOKE ALL ON TABLE private.uci_results_manual_queue FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON SEQUENCE private.uci_results_manual_queue_id_seq FROM PUBLIC, anon, authenticated, service_role;

CREATE OR REPLACE FUNCTION private.dispatch_uci_results_workflow(
  p_race_id text,
  p_stage integer,
  p_ignore_window boolean
)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'public', 'private', 'pg_temp'
AS $function$
BEGIN
  IF NOT ((SELECT private.is_admin()) OR (SELECT auth.role()) = 'service_role') THEN
    RAISE EXCEPTION 'La operación requiere permisos de administración' USING ERRCODE = '42501';
  END IF;
  IF p_race_id IS NOT NULL AND btrim(p_race_id) = '' THEN
    RAISE EXCEPTION 'Falta p_race_id';
  END IF;
  IF p_stage IS NOT NULL AND p_race_id IS NULL THEN
    RAISE EXCEPTION 'Una etapa requiere p_race_id';
  END IF;
  IF p_race_id IS NOT NULL AND NOT EXISTS (
    SELECT 1 FROM public.races WHERE id = p_race_id
  ) THEN
    RAISE EXCEPTION 'Carrera inexistente: %', p_race_id;
  END IF;

  -- Un doble clic o una repetición inmediata no crea trabajo duplicado.
  PERFORM pg_advisory_xact_lock(hashtext('uci_results_manual_queue'));
  IF NOT EXISTS (
    SELECT 1
    FROM private.uci_results_manual_queue q
    WHERE q.status IN ('pending', 'running')
      AND q.race_id IS NOT DISTINCT FROM p_race_id
      AND q.stage_number IS NOT DISTINCT FROM p_stage
      AND q.ignore_window = COALESCE(p_ignore_window, false)
  ) THEN
    INSERT INTO private.uci_results_manual_queue (
      race_id, stage_number, ignore_window, requested_by
    ) VALUES (
      p_race_id, p_stage, COALESCE(p_ignore_window, false), auth.uid()
    );
  END IF;

  RETURN 'queued';
END;
$function$;

CREATE OR REPLACE FUNCTION private.claim_uci_results_manual_request()
RETURNS TABLE (
  request_id bigint,
  race_id text,
  stage_number integer,
  ignore_window boolean
)
LANGUAGE sql
SECURITY DEFINER
SET search_path TO 'private', 'pg_temp'
AS $function$
  WITH candidate AS (
    SELECT q.id
    FROM private.uci_results_manual_queue q
    WHERE q.status = 'pending'
       OR (q.status = 'running' AND q.started_at < now() - interval '30 minutes')
    ORDER BY q.requested_at, q.id
    FOR UPDATE SKIP LOCKED
    LIMIT 1
  ), claimed AS (
    UPDATE private.uci_results_manual_queue q
    SET status = 'running',
        started_at = now(),
        finished_at = NULL,
        attempts = q.attempts + 1,
        error_message = NULL
    FROM candidate c
    WHERE q.id = c.id
    RETURNING q.id, q.race_id, q.stage_number, q.ignore_window
  )
  SELECT id, race_id, stage_number, ignore_window FROM claimed;
$function$;

CREATE OR REPLACE FUNCTION private.finish_uci_results_manual_request(
  p_request_id bigint,
  p_success boolean,
  p_error text DEFAULT NULL
)
RETURNS void
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path TO 'private', 'pg_temp'
AS $function$
BEGIN
  UPDATE private.uci_results_manual_queue
  SET status = CASE WHEN p_success THEN 'done' ELSE 'error' END,
      finished_at = now(),
      error_message = CASE WHEN p_success THEN NULL ELSE left(COALESCE(p_error, 'Error sin detalle'), 1000) END
  WHERE id = p_request_id
    AND status = 'running';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'Solicitud manual no reclamada: %', p_request_id;
  END IF;
END;
$function$;

GRANT USAGE ON SCHEMA private TO cc_results_worker;
REVOKE ALL ON FUNCTION private.claim_uci_results_manual_request() FROM PUBLIC, anon, authenticated, service_role;
REVOKE ALL ON FUNCTION private.finish_uci_results_manual_request(bigint, boolean, text) FROM PUBLIC, anon, authenticated, service_role;
GRANT EXECUTE ON FUNCTION private.claim_uci_results_manual_request() TO cc_results_worker;
GRANT EXECUTE ON FUNCTION private.finish_uci_results_manual_request(bigint, boolean, text) TO cc_results_worker;
